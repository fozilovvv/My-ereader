"""Нормализация текста для поиска.

SQLite умеет игнорировать регистр только у латиницы, а LOWER()/UPPER()
в нём тоже работают лишь с ASCII. Поэтому приводим строки к единому виду
средствами Python — он знает про регистр всех алфавитов — и храним
готовый результат в отдельном поле.
"""
import re

SPACES = re.compile(r'\s+')


def normalize(text: str) -> str:
    """«Хранитель тихой станции» -> «хранитель тихой станции».

    Заодно приравниваем «ё» к «е»: иначе «ёлка» и «елка» не найдут друг друга.
    """
    lowered = (text or '').lower().replace('ё', 'е')
    return SPACES.sub(' ', lowered).strip()


def terms(query: str) -> list[str]:
    """Запрос -> список слов. «тихой  ХРАНИТЕЛЬ» -> ['тихой', 'хранитель']."""
    return [word for word in normalize(query).split(' ') if word]
